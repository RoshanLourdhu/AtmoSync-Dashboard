"""AtmoSync Data Quality Report Generator.

Computes a normalized quality score (0-100%) from tabular or record validation
results and exports structured JSON reports."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

try:
    from .validator import validate_sensor_data
except ImportError:
    from validator import validate_sensor_data


def generate_quality_report(
    data: Any,
    required_columns: list[str] | None = None,
) -> dict[str, Any]:
    """Generate a structured data quality summary and scoring metric.

    Args:
        data: Input records (list of dicts or DataFrame).
        required_columns: Optional column subset. Defaults to official 7-field schema.

    Returns:
        dict[str, Any]: Consolidated metrics including quality_score (0-100%).
    """
    validation = validate_sensor_data(data, required_columns=required_columns)

    if validation.get("status") == "Failed":
        return validation

    total_records = validation.get("total_records", 0)
    # Count original missing values and also treat non‑numeric conversions as missing
    numeric_invalid = sum(validation["invalid_numeric_values"].values())
    missing_count = sum(
        validation["missing_values"].values()
    ) + numeric_invalid
    # Reflect the combined count in the report
    validation["missing_values"] = missing_count

    duplicate_count = validation.get("duplicate_records", 0)
    invalid_timestamps = validation.get("invalid_timestamps", 0)
    invalid_humidity = validation.get("invalid_humidity_records", 0)
    invalid_vibration = validation.get("invalid_vibration_records", 0)
    invalid_temperature = validation.get("invalid_temperature_records", 0)
    invalid_numeric = sum(validation.get("invalid_numeric_values", {}).values())

    # Calculate data quality score (0 - 100%)
    if total_records == 0:
        quality_score = 0.0
    else:
        issues = (
            missing_count
            + duplicate_count
            + invalid_timestamps
            + invalid_humidity
            + invalid_vibration
            + invalid_temperature
            + invalid_numeric
        )
        # Bounded score penalized by total issue density
        quality_score = max(
            0.0,
            round((1.0 - min(issues / (total_records * 5), 1.0)) * 100.0, 2),
        )

    return {
        "total_records": total_records,
        "quality_score": quality_score,
        "missing_values": missing_count,
        "duplicate_records": duplicate_count,
        "invalid_timestamps": invalid_timestamps,
        "invalid_numeric_values": invalid_numeric,
        "invalid_humidity_records": invalid_humidity,
        "invalid_vibration_records": invalid_vibration,
        "invalid_temperature_records": invalid_temperature,
        "outliers": validation.get("outliers", {}),
        "validation_status": validation.get("status"),
    }

# Preserve the original implementation under a private name for internal calls
_generate_quality_report_impl = generate_quality_report

def export_report(
    report: dict[str, Any],
    output_path: str | Path = "data_quality_report.json",
) -> str:
    """Export quality report as formatted JSON.

    Args:
        report: Dictionary summary generated by generate_quality_report.
        output_path: Destination file path.

    Returns:
        str: Absolute or relative output file path string.
    """
    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)

    with output.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=4)

    return str(output)


