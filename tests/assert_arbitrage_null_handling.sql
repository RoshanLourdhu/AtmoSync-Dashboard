SELECT *
FROM {{ ref('fct_commodity_arbitrage') }}
WHERE
       COMMODITY_NAME IS NULL
    OR BUY_LOCATION IS NULL
    OR SELL_LOCATION IS NULL
    OR BUY_PRICE IS NULL
    OR SELL_PRICE IS NULL
    OR BUY_QUANTITY IS NULL
    OR SELL_QUANTITY IS NULL
    OR TRADEABLE_QUANTITY IS NULL
    OR PRICE_DIFFERENCE IS NULL
    OR ESTIMATED_GROSS_PROFIT IS NULL
    OR ARBITRAGE_STATUS IS NULL