WITH source AS (

    SELECT *
    FROM {{ source('sensor_source', 'RAW_COMMODITY') }}

),

cleaned AS (

    SELECT
        COMMODITY_ID,
        TRIM(COMMODITY_NAME) AS COMMODITY_NAME,
        TRIM(CATEGORY) AS CATEGORY,
        CAST(PRICE AS NUMBER(10,2)) AS PRICE,
        CAST(QUANTITY AS NUMBER(10,2)) AS QUANTITY,
        LOCATION,
        RECORDED_AT,
        RECEIVED_DATE,

    FROM source

)

SELECT *
FROM cleaned
WHERE COMMODITY_ID IS NOT NULL
  AND COMMODITY_NAME IS NOT NULL
  AND PRICE IS NOT NULL
  AND QUANTITY IS NOT NULL